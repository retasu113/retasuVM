#!/usr/bin/env python3
# Merge qemu-aarch64 oracle outputs into nb_cases.swift, after verifying the
# independent Python model agrees with the oracle on every case.
import struct, subprocess, sys

raw = open("oracle_nb_out.bin", "rb").read()
cases = []
for l in open("nb_cases.txt"):
    p = l.split()
    cases.append((p[0], int(p[1], 16), (int(p[2], 16), int(p[3], 16)), (int(p[4], 16), int(p[5], 16))))
assert len(raw) == len(cases) * 16, f"oracle output size {len(raw)} != {len(cases) * 16}"
oracle = {}
for i, (name, *_rest) in enumerate(cases):
    lo, hi = struct.unpack_from("<QQ", raw, i * 16)
    oracle[name] = (lo, hi)

model = {}
out = subprocess.run([sys.executable, "model_nb.py"], capture_output=True, text=True)
for l in out.stdout.strip().split("\n"):
    p = l.split()
    model[p[0]] = (int(p[1], 16), int(p[2], 16))

agree = sum(1 for n in oracle if oracle[n] == model[n])
print(f"model vs oracle: {agree}/{len(oracle)} agree")
for n in oracle:
    if oracle[n] != model[n]:
        print("DISAGREE", n, "oracle", tuple("%016X" % v for v in oracle[n]),
              "model", tuple("%016X" % v for v in model[n]))
if agree != len(oracle):
    sys.exit(1)

lines = ["// Generated by gen_nb.py; expectations from the qemu-aarch64 oracle (merge_nb.py).",
         "let nbCases: [Case] = ["]
for (name, w, vd, vn) in cases:
    e = oracle[name]
    lines.append(f'    Case(name: "{name}", word: 0x{w:08X}, rd: 0, rn: 1, '
                 f'vd: (0x{vd[0]:016X}, 0x{vd[1]:016X}), vn: (0x{vn[0]:016X}, 0x{vn[1]:016X}), '
                 f'e: (0x{e[0]:016X}, 0x{e[1]:016X})),')
lines.append("]")
open("nb_cases.swift", "w").write("\n".join(lines) + "\n")
print("nb_cases.swift written with oracle expectations")
