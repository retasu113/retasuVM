#!/usr/bin/env python3
# Neighbour audit for QEMU's two-register-miscellaneous integer group
# (a64.decode, @qrr_e listing): every encoding that can reach our
# executeSIMDTwoRegMisc — bits20:16 (hi) in {00000, 00001}, opcode
# bits15:11 odd (bit11=1 is required by our dispatch), U in {0,1},
# size in {0,1,2}, Q in {0,1}: 2*16*2*3*2 = 384 words.
# For each word the qemu-aarch64 oracle decides validity + result, and
# our engine (audit_main.swift) is classified against it:
#   oracle valid   + engine THROW        -> MISSING (clean miss)
#   oracle valid   + engine wrong value  -> MISROUTE (convicted)
#   oracle invalid + engine executes     -> EXEC-UNDEF (divergence)
#   oracle invalid + engine THROW        -> consistent
import random, os

rng = random.Random(20261119)

def r128():
    return (rng.getrandbits(64), rng.getrandbits(64))

cases = []  # (name, word, rd, rn, vd, vn)
for hi in (0, 1):
    for opc in range(1, 32, 2):
        for u in (0, 1):
            for size in (0, 1, 2):
                for q in (0, 1):
                    w = (0x0E200000 | (q << 30) | (u << 29) | (size << 22)
                         | (hi << 16) | (opc << 11) | (1 << 5) | 0)
                    name = f"a_h{hi}o{opc}u{u}s{size}q{q}"
                    cases.append((name, w, 0, 1, r128(), r128()))

os.makedirs("audit_oracle", exist_ok=True)

def oracle_s(batch):
    inp = []
    for c in batch:
        for v in (c[4], c[5]):
            inp += [v[0], v[1]]
    lines = [".text\n.globl _start\n_start:"]
    lines.append("    adrp x10, outputs\n    add x10, x10, :lo12:outputs")
    lines.append("    adrp x9, inputs\n    add x9, x9, :lo12:inputs")
    for i, c in enumerate(batch):
        name, w, rd, rn = c[0], c[1], c[2], c[3]
        base = i * 32
        lines.append(f"    ldr q{rd}, [x9, #{base}]")
        lines.append(f"    ldr q{rn}, [x9, #{base + 16}]")
        lines.append(f"    .word 0x{w:08x}  // {name}")
        lines.append(f"    str q{rd}, [x10, #{i * 16}]")
    total = len(batch) * 16
    hexlen = total * 2 + total // 16
    lines.append(f"""
    adrp x11, outputs
    add x11, x11, :lo12:outputs
    adrp x12, hexbuf
    add x12, x12, :lo12:hexbuf
    mov x13, #0
print_loop:
    cmp x13, #{total}
    b.ge print_done
    ldrb w14, [x11, x13]
    lsr w15, w14, #4
    and w14, w14, #0xf
    adrp x16, hexdigits
    add x16, x16, :lo12:hexdigits
    ldrb w15, [x16, x15]
    ldrb w14, [x16, x14]
    mov x17, x13
    lsl x17, x17, #1
    add x17, x17, x13, lsr #4
    strb w15, [x12, x17]
    add x17, x17, #1
    strb w14, [x12, x17]
    add x13, x13, #1
    mov x17, x13
    and x17, x17, #0xf
    cbnz x17, print_loop
    mov x17, x13
    lsl x17, x17, #1
    add x17, x17, x13, lsr #4
    mov w14, #10
    strb w14, [x12, x17]
    b print_loop
print_done:
    mov x0, #1
    mov x1, x12
    mov x2, #{hexlen}
    mov x8, #64
    svc #0
    mov x0, #0
    mov x8, #93
    svc #0
    .section .data
    .align 4
inputs:""")
    for v in inp:
        lines.append(f"    .quad 0x{v:016x}")
    lines.append(f"""outputs:
    .zero {total}
hexbuf:
    .zero {hexlen + 16}
hexdigits:
    .ascii "0123456789abcdef"
""")
    return "\n".join(lines) + "\n"

# batches keyed by (hi, opc)
batches = {}
for c in cases:
    hi = (c[1] >> 16) & 0x1F
    opc = (c[1] >> 11) & 0x1F
    batches.setdefault((hi, opc), []).append(c)
for (hi, opc), batch in sorted(batches.items()):
    with open(f"audit_oracle/batch_h{hi}o{opc}.s", "w") as f:
        f.write(oracle_s(batch))
    with open(f"audit_oracle/batch_h{hi}o{opc}.txt", "w") as f:
        for c in batch:
            f.write(c[0] + "\n")
# single-case sources for fallback classification of dead batches
for c in cases:
    with open(f"audit_oracle/one_{c[0]}.s", "w") as f:
        f.write(oracle_s([c]))

with open("audit_cases.swift", "w") as f:
    f.write("// generated by gen_audit.py — expected merged by merge_audit.py\n")
    f.write("let auditCases: [Case] = [\n")
    for (name, w, rd, rn, vd, vn) in cases:
        f.write(f'    Case(name: "{name}", word: 0x{w:08X}, rd: {rd}, rn: {rn}, '
                f'vd: (0x{vd[0]:016X}, 0x{vd[1]:016X}), vn: (0x{vn[0]:016X}, 0x{vn[1]:016X}), '
                f'e: (0, 0)),\n')
    f.write("]\n")
with open("audit_cases_list.txt", "w") as f:
    for c in cases:
        f.write(c[0] + "\n")
print(f"{len(cases)} audit cases, {len(batches)} batches")
