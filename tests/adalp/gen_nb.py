#!/usr/bin/env python3
# Dedicated differential for the convicted neighbours:
#   (0,7)  SUQADD / USQADD   (U semantics were swapped in our engine)
#   (1,5)  XTN / SQXTUN      (Q=1 half handling + SQXTUN saturation)
#   (1,9)  SQXTN / UQXTN     (Q=1 half handling)
# Method identical to the ADALP differential: qemu-aarch64 oracle (oracle_nb.s)
# is the ground truth; an independent Python model must agree with it 100%
# before the engine is judged.
import random, struct

random.seed(0x5EED)

def rand128():
    return random.getrandbits(64), random.getrandbits(64)

PATTERNS = {
    "ones":  (0xFFFFFFFFFFFFFFFF, 0xFFFFFFFFFFFFFFFF),
    "zero":  (0x0000000000000000, 0x0000000000000000),
    "b80":   (0x8080808080808080, 0x8080808080808080),
    "b7f":   (0x7F7F7F7F7F7F7F7F, 0x7F7F7F7F7F7F7F7F),
    "alt":   (0xAAAAAAAAAAAAAAAA, 0x5555555555555555),
    "signs": (0x80007FFF80007FFF, 0x7FFF80007FFF8000),
}

cases = []  # (name, word, rd, rn, vd, vn)

def add(name, word, vd, vn):
    cases.append((name, word, 0, 1, vd, vn))

# (0,7): word = 0x0E200000 | Q<<30 | U<<29 | size<<22 | 7<<11 | rn<<5 | rd
for u in (0, 1):
    op = "suqadd" if u == 0 else "usqadd"
    for size in (0, 1, 2):
        for q in (0, 1):
            w = 0x0E200000 | (q << 30) | (u << 29) | (size << 22) | (7 << 11) | (1 << 5) | 0
            for i in range(3):
                add(f"{op}_s{size}q{q}_r{i}", w, rand128(), rand128())
            for pn, pv in PATTERNS.items():
                add(f"{op}_s{size}q{q}_{pn}", w, pv, rand128())
                add(f"{op}_s{size}q{q}_n{pn}", w, rand128(), pv)

# (1,5) / (1,9): word = 0x0E200000 | Q<<30 | U<<29 | size<<22 | 1<<16 | opc<<11 | rn<<5 | rd
for opc, names in ((5, ("xtn", "sqxtun")), (9, ("sqxtn", "uqxtn"))):
    for u in (0, 1):
        op = names[u]
        for size in (0, 1, 2):
            for q in (0, 1):
                w = 0x0E200000 | (q << 30) | (u << 29) | (size << 22) | (1 << 16) | (opc << 11) | (1 << 5) | 0
                for i in range(3):
                    add(f"{op}_s{size}q{q}_r{i}", w, rand128(), rand128())
                for pn, pv in PATTERNS.items():
                    add(f"{op}_s{size}q{q}_{pn}", w, pv, rand128())
                    add(f"{op}_s{size}q{q}_n{pn}", w, rand128(), pv)

print(f"nb cases: {len(cases)}")

# ---- oracle_nb.s (same batch pattern as oracle.s) ----
lines = [".text", ".globl _start", "_start:",
         "    adrp x10, outputs", "    add x10, x10, :lo12:outputs",
         "    adrp x9, inputs", "    add x9, x9, :lo12:inputs"]
inputs = []
for i, (name, w, rd, rn, vd, vn) in enumerate(cases):
    off = i * 32
    lines.append(f"    ldr q{rd}, [x9, #{off}]")
    lines.append(f"    ldr q{rn}, [x9, #{off + 16}]")
    lines.append(f"    .word 0x{w:08x}  // {name}")
    lines.append(f"    str q{rd}, [x10, #{i * 16}]")
    inputs += [vd[0], vd[1], vn[0], vn[1]]
lines += ["    mov x0, #1", "    mov x1, x10", f"    mov x2, #{len(cases) * 16}",
          "    mov x8, #64", "    svc #0",
          "    mov x0, #0", "    mov x8, #93", "    svc #0",
          ".section .data", "inputs:"]
for i in range(0, len(inputs), 2):
    lines.append(f"    .quad 0x{inputs[i]:016x}, 0x{inputs[i + 1]:016x}")
lines.append("outputs:")
lines.append(f"    .fill {len(cases) * 2}, 8, 0")
open("oracle_nb.s", "w").write("\n".join(lines) + "\n")

# ---- cases file with placeholder expectations (merged later) ----
out = ["// Generated by gen_nb.py; expectations merged from the qemu-aarch64 oracle.",
       "let nbCases: [Case] = ["]
for (name, w, rd, rn, vd, vn) in cases:
    out.append(f'    Case(name: "{name}", word: 0x{w:08X}, rd: {rd}, rn: {rn}, '
               f'vd: (0x{vd[0]:016X}, 0x{vd[1]:016X}), vn: (0x{vn[0]:016X}, 0x{vn[1]:016X}), '
               f'e: (0x0000000000000000, 0x0000000000000000)),')
out.append("]")
open("nb_cases.swift", "w").write("\n".join(out) + "\n")

# stash the case list for the model / merger
with open("nb_cases.txt", "w") as f:
    for (name, w, rd, rn, vd, vn) in cases:
        f.write(f"{name} {w:08X} {vd[0]:016X} {vd[1]:016X} {vn[0]:016X} {vn[1]:016X}\n")
print("wrote oracle_nb.s, nb_cases.swift, nb_cases.txt")
